param(
    [string]$Key = $env:CURSEFORGE_API_KEY,
    [string]$OutFile = ""
)

# 把 CurseForge API Key 加密后生成为 C# 源文件(不进仓库)。
# 用法:
#   $env:CURSEFORGE_API_KEY = "cf_xxx"
#   powershell -File tools\embed-cf-key.ps1
# 或:
#   powershell -File tools\embed-cf-key.ps1 -Key "cf_xxx"

$ErrorActionPreference = 'Stop'

if ([string]::IsNullOrWhiteSpace($Key)) {
    throw "没有 Key:设置环境变量 CURSEFORGE_API_KEY 或传 -Key"
}

$root = Split-Path -Parent $PSScriptRoot
if ([string]::IsNullOrWhiteSpace($OutFile)) {
    $OutFile = Join-Path $root 'src\Fuse.App\Generated\CfKey.g.cs'
}

# 版本号参与 keystream,保证不同版本的密文不同
[xml]$proj = Get-Content (Join-Path $root 'src\Fuse.App\Fuse.App.csproj') -Encoding UTF8
$version = ($proj.Project.PropertyGroup | ForEach-Object { $_.Version } | Where-Object { $_ } | Select-Object -First 1)
if (-not $version) { throw '读不到 Fuse.App.csproj 的 <Version>' }

function New-RandomBytes([int]$length) {
    $bytes = New-Object byte[] $length
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($bytes)
    $rng.Dispose()
    return $bytes
}

$keyBytes = [System.Text.Encoding]::UTF8.GetBytes($Key)
$salt = New-RandomBytes 16
$pepperA = New-RandomBytes 16
$pepperB = New-RandomBytes 16

# material = pepperA || salt || pepperB || UTF8(version)
$versionBytes = [System.Text.Encoding]::UTF8.GetBytes($version)
$material = New-Object byte[] ($pepperA.Length + $salt.Length + $pepperB.Length + $versionBytes.Length)
$offset = 0
[Array]::Copy($pepperA, 0, $material, $offset, $pepperA.Length); $offset += $pepperA.Length
[Array]::Copy($salt, 0, $material, $offset, $salt.Length); $offset += $salt.Length
[Array]::Copy($pepperB, 0, $material, $offset, $pepperB.Length); $offset += $pepperB.Length
[Array]::Copy($versionBytes, 0, $material, $offset, $versionBytes.Length)

# keystream: SHA256(material || counterLE32),逐块
$sha = [System.Security.Cryptography.SHA256]::Create()
$buffer = New-Object byte[] ($material.Length + 4)
[Array]::Copy($material, 0, $buffer, 0, $material.Length)
$stream = New-Object System.IO.MemoryStream
$index = 0
while ($stream.Length -lt $keyBytes.Length) {
    $counter = [BitConverter]::GetBytes([int]$index)
    [Array]::Copy($counter, 0, $buffer, $material.Length, 4)
    $block = $sha.ComputeHash($buffer)
    $stream.Write($block, 0, $block.Length)
    $index++
}
$sha.Dispose()
$keystream = $stream.ToArray()
$stream.Dispose()

$cipher = New-Object byte[] $keyBytes.Length
for ($i = 0; $i -lt $keyBytes.Length; $i++) {
    $cipher[$i] = $keyBytes[$i] -bxor $keystream[$i]
}

# 打包成 int[](小端),字符串搜索看不到
$intCount = [Math]::Ceiling($cipher.Length / 4.0)
$packed = New-Object int[] $intCount
for ($i = 0; $i -lt $cipher.Length; $i++) {
    $slot = [int][Math]::Floor($i / 4)
    $packed[$slot] = $packed[$slot] -bor ([int]$cipher[$i] -shl (8 * ($i % 4)))
}

function Format-Bytes([byte[]]$bytes) {
    ($bytes | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', '
}
function Format-Ints([int[]]$ints) {
    $parts = foreach ($v in $ints) {
        $u = [BitConverter]::ToUInt32([BitConverter]::GetBytes([int]$v), 0)
        'unchecked((int)0x{0:X8})' -f $u
    }
    $parts -join ', '
}

$dir = Split-Path -Parent $OutFile
if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }

$content = @"
// <auto-generated />
// 由 tools/embed-cf-key.ps1 生成,包含加密后的 CurseForge API Key。
// 不要提交:src/Fuse.App/Generated/ 已在 .gitignore 中。
namespace Fuse.App;

internal static class CfKeyGenerated
{
    internal const string Version = "$version";
    internal static readonly byte[] Salt = { $(Format-Bytes $salt) };
    internal static readonly byte[] PepperA = { $(Format-Bytes $pepperA) };
    internal static readonly byte[] PepperB = { $(Format-Bytes $pepperB) };
    internal static readonly int[] Data = { $(Format-Ints $packed) };
}
"@

[System.IO.File]::WriteAllText($OutFile, $content, (New-Object System.Text.UTF8Encoding($true)))
Write-Host ('generated: ' + $OutFile)
Write-Host ('key length: ' + $keyBytes.Length + ' bytes, version: ' + $version)
